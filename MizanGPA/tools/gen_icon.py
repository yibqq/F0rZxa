"""
Generates the launcher icon layers: a GPA gauge (as in the app) with the word "GPA" inside.

The letters are outlines of Nunito Black (SIL Open Font License), converted to vector paths so the
font file itself is not needed. Usage:  python3 gen_icon.py <Nunito[wght].ttf> <res dir>
"""
import math, sys, os
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
sys.path.insert(0, os.path.dirname(__file__))
from gpa_path import gpa_path

font, res = sys.argv[1], sys.argv[2]
black = os.path.join(os.path.dirname(os.path.abspath(res)), "nunito900.tmp.ttf")
instancer.instantiateVariableFont(TTFont(font), {"wght": 900}).save(black)
text, _ = gpa_path(black, 53.0, 54, 12.0, -0.9)
os.remove(black)

cx = cy = 54.0
r = 24.0
def pt(deg):
    a = math.radians(deg)
    return cx + r * math.cos(a), cy + r * math.sin(a)
f = lambda v: f"{v:.2f}"
sx, sy = pt(135); tx, ty = pt(45); ex, ey = pt(135 + 212)
track = f"M{f(sx)},{f(sy)} A{r:.0f},{r:.0f} 0 1,1 {f(tx)},{f(ty)}"
prog = f"M{f(sx)},{f(sy)} A{r:.0f},{r:.0f} 0 1,1 {f(ex)},{f(ey)}"

def layer(track_color, prog_color, text_color, dot_color, dot_ring):
    ring = (f'    <path android:fillColor="{dot_ring}" android:pathData="M{f(ex)},{f(ey)} '
            f'm-7.2,0 a7.2,7.2 0 1,0 14.4,0 a7.2,7.2 0 1,0 -14.4,0" />\n') if dot_ring else ""
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_icon.py: GPA gauge with "GPA" (Nunito Black outlines, OFL). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:strokeColor="{track_color}" android:strokeWidth="6.5" android:strokeLineCap="round" android:pathData="{track}" />
    <path android:strokeColor="{prog_color}" android:strokeWidth="6.5" android:strokeLineCap="round" android:pathData="{prog}" />
    <path android:fillColor="{text_color}" android:pathData="{text}" />
{ring}    <path android:fillColor="{dot_color}" android:pathData="M{f(ex)},{f(ey)} m-4.6,0 a4.6,4.6 0 1,0 9.2,0 a4.6,4.6 0 1,0 -9.2,0" />
</vector>
'''

open(f"{res}/drawable/ic_launcher_foreground.xml", "w").write(layer("#40FFFFFF", "#FFFFFF", "#FFFFFF", "#FFC845", "#0C5E72"))
open(f"{res}/drawable/ic_launcher_monochrome.xml", "w").write(layer("#66FFFFFF", "#FFFFFF", "#FFFFFF", "#FFFFFF", None))
print("icon written")
